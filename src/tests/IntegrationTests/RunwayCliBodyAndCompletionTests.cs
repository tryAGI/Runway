using System.Text.Json;
using AwesomeAssertions;

namespace Runway.IntegrationTests;

/// <summary>
/// Covers the two input paths that bypass the friendly flags — a posted JSON body and the generated
/// `runway api …` group — plus the generated shell completion scripts. Nothing here reaches the API.
/// </summary>
[TestClass]
public sealed class RunwayCliBodyAndCompletionTests
{
    private static readonly Dictionary<string, string?> OfflineEnvironment = new(StringComparer.Ordinal)
    {
        ["RUNWAY_BASE_URL"] = "http://127.0.0.1:9",
        ["RUNWAY_API_KEY"] = "key_test_dummy",
        ["RUNWAY_DOTENV_DISABLED"] = "1",
    };

    private static Task<CliResult> RunAsync(string arguments) =>
        CliHarness.RunCliAsync(arguments, environment: OfflineEnvironment);

    [TestMethod]
    public void JsonBodyValidator_ReportsOutOfEnumValues()
    {
        var violations = RunwayCliJsonBodyValidator.FindViolations(
            """{"model":"magnific_video_upscaler_creative","videoUri":"https://example.com/a.mp4","flavor":"viv1d"}""");

        violations.Should().HaveCount(1);
        violations[0].Should().Contain("flavor").And.Contain("vivid, natural");
    }

    [TestMethod]
    public void JsonBodyValidator_ReportsEveryViolationAtOnce()
    {
        // A CI run should not have to fix one problem per attempt.
        var violations = RunwayCliJsonBodyValidator.FindViolations(
            """{"model":"gen4.5","promptText":"x","ratio":"9999:1","duration":5,"outputFormat":"tiff"}""");

        violations.Should().HaveCountGreaterThanOrEqualTo(2);
        string.Join(" ", violations).Should().Contain("ratio").And.Contain("outputFormat");
    }

    [TestMethod]
    public void JsonBodyValidator_IsSilentWhenItCannotBeSure()
    {
        // Unknown model: the spec has not described it yet, so nothing is blocked.
        RunwayCliJsonBodyValidator.FindViolations("""{"model":"kling_4","ratio":"anything"}""").Should().BeEmpty();

        // Not an object, no model, or unparseable: the deserializer reports those better than we can.
        RunwayCliJsonBodyValidator.FindViolations("""{"ratio":"9999:1"}""").Should().BeEmpty();
        RunwayCliJsonBodyValidator.FindViolations("[1,2,3]").Should().BeEmpty();
        RunwayCliJsonBodyValidator.FindViolations("{not json").Should().BeEmpty();
        RunwayCliJsonBodyValidator.FindViolations(null).Should().BeEmpty();

        // A model on two endpoints: a value valid on either one is accepted, so no false positive.
        RunwayCliJsonBodyValidator.FindViolations(
            """{"model":"veo3.1","promptText":"x","ratio":"1280:720","duration":6}""").Should().BeEmpty();

        // ...but a value invalid on both is still reported.
        RunwayCliJsonBodyValidator.FindViolations(
            """{"model":"veo3.1","promptText":"x","ratio":"9999:1"}""").Should().HaveCount(1);
    }

    [TestMethod]
    public void JsonBodyValidator_ChecksNestedPresetAndDiscriminatorValues()
    {
        RunwayCliJsonBodyValidator.FindViolations(
            """{"model":"eleven_multilingual_v2","promptText":"hi","voice":{"type":"runway-preset","presetId":"clara"}}""")
            .Should().ContainSingle().Which.Should().Contain("voice.presetId");

        RunwayCliJsonBodyValidator.FindViolations(
            """{"model":"eleven_multilingual_sts_v2","voice":{"type":"runway-preset","presetId":"Maya"},"media":{"type":"hologram","uri":"https://example.com/a.mp3"}}""")
            .Should().ContainSingle().Which.Should().Contain("media.type");
    }

    [TestMethod]
    public async Task CuratedJsonFlagRejectsABadBody()
    {
        var result = await RunAsync(
            """video-upscale --json {"model":"magnific_video_upscaler_creative","videoUri":"https://example.com/a.mp4","flavor":"viv1d"}""")
            .ConfigureAwait(false);

        result.ExitCode.Should().Be(2);
        result.Stderr.Should().Contain("does not match the Runway OpenAPI spec").And.Contain("vivid, natural");
        result.Stdout.Should().BeEmpty();
    }

    [TestMethod]
    public async Task GeneratedApiGroupRejectsABadBodyToo()
    {
        // `GeneratedApi/` is regenerated by generate.sh, so the check is attached from Program.cs when
        // the command tree is registered. This test fails if that wiring is ever lost.
        var result = await RunAsync(
            """api start-generating create-video-upscale --input {"model":"magnific_video_upscaler_creative","videoUri":"https://example.com/a.mp4","flavor":"viv1d"}""")
            .ConfigureAwait(false);

        result.ExitCode.Should().Be(2);
        result.Stderr.Should().Contain("vivid, natural");
    }

    [TestMethod]
    public async Task BodiesPipedIntoTheGeneratedGroupAreValidatedToo()
    {
        const string bad =
            """{"model":"magnific_video_upscaler_creative","videoUri":"https://example.com/a.mp4","flavor":"viv1d"}""";

        // A parse validator cannot read stdin — the stream is consumable once and the handler needs the
        // same content — so the body is buffered before invocation, checked, and handed back through
        // Console.In. Both spellings of the flag go through that path.
        foreach (var arguments in new[]
                 {
                     "api start-generating create-video-upscale --input -",
                     "api start-generating create-video-upscale --input=-",
                     "api start-generating create-video-upscale --request-file -",
                 })
        {
            var result = await CliHarness.RunCliAsync(
                arguments, environment: OfflineEnvironment, standardInput: bad).ConfigureAwait(false);

            result.ExitCode.Should().Be(2, $"`{arguments}` should reject the piped body");
            result.Stderr.Should().Contain("vivid, natural");
        }
    }

    [TestMethod]
    public async Task AGoodPipedBodyStillReachesTheHandler()
    {
        // The re-injected stdin must carry the identical content, otherwise valid bodies would break.
        const string good =
            """{"model":"magnific_video_upscaler_creative","videoUri":"https://example.com/a.mp4","flavor":"vivid"}""";

        var result = await CliHarness.RunCliAsync(
            "api start-generating create-video-upscale --input -",
            environment: OfflineEnvironment,
            standardInput: good).ConfigureAwait(false);

        // 1, not 2: the body passed validation and the request failed at the closed port.
        result.ExitCode.Should().Be(1);
        result.Stderr.Should().NotContain("does not match the Runway OpenAPI spec");
    }

    [TestMethod]
    public async Task CompletionScriptsAreEmittedForEverySupportedShell()
    {
        foreach (var shell in RunwayCliCompletion.SupportedShells)
        {
            var result = await RunAsync($"completion {shell}").ConfigureAwait(false);
            result.ExitCode.Should().Be(0, $"{shell} is a supported shell");
            result.Stderr.Should().BeEmpty();
            result.Stdout.Should().Contain("runway");

            // Model lists come from the spec, so a model added by a refresh appears without a code change.
            result.Stdout.Should().Contain("seedance2_5");
            result.Stdout.Should().Contain("muse_image");
        }

        var unsupported = await RunAsync("completion powershell").ConfigureAwait(false);
        unsupported.ExitCode.Should().Be(2);
        unsupported.Stderr.Should().Contain("bash, zsh, fish");
    }

    [TestMethod]
    public async Task CompletionScriptsCoverTheCommandsAndTheGlobalOptions()
    {
        var bash = await RunAsync("completion bash").ConfigureAwait(false);

        // Spot-check that the tree was walked rather than hand-listed.
        bash.Stdout.Should().Contain("video-upscale").And.Contain("image-upscale").And.Contain("completion");
        bash.Stdout.Should().Contain("--quiet").And.Contain("--format");
        bash.Stdout.Should().Contain("text json", "--format values are completed");
    }

    [TestMethod]
    public void EndpointsUsedForModelCompletionAllExistInTheSpec()
    {
        // Guard against a typo'd endpoint name silently producing an empty completion list.
        foreach (var endpoint in new[]
                 {
                     RunwayCliGeneration.TextToVideoEndpoint,
                     RunwayCliGeneration.ImageToVideoEndpoint,
                     RunwayCliGeneration.VideoToVideoEndpoint,
                     RunwayCliGeneration.TextToImageEndpoint,
                     RunwayCliGeneration.VideoUpscaleEndpoint,
                     RunwayCliGeneration.ImageUpscaleEndpoint,
                     RunwayCliGeneration.TextToSpeechEndpoint,
                     RunwayCliGeneration.SoundEffectEndpoint,
                     RunwayCliGeneration.CharacterPerformanceEndpoint,
                 })
        {
            RunwayModelSchema.ModelsForEndpoint(endpoint)
                .Should().NotBeEmpty($"{endpoint} should resolve to at least one model");
        }
    }
}
